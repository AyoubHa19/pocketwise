import type { NextConfig } from "next";

const nextConfig: NextConfig = {
  // Basic protection on every page: no showing Pocketwise inside another
  // site's frame (clickjacking), no guessing file types, addresses of
  // other sites never told which page you came from, and no browser
  // features the app doesn't use. (Vercel adds HTTPS-only itself.)
  async headers() {
    return [
      {
        source: "/(.*)",
        headers: [
          { key: "X-Frame-Options", value: "DENY" },
          { key: "Content-Security-Policy", value: "frame-ancestors 'none'" },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          { key: "Permissions-Policy", value: "camera=(self), microphone=(), geolocation=(), payment=()" },
        ],
      },
    ];
  },
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
};

export default nextConfig;
